/**
 * Filter evidence-based exercises by muscle group and optional rank limit
 */
export function getTopRankedExercisesForMuscle(
  muscleGroup: string,
  limit = 5
): EvidenceExercise[] {
  if (muscleGroup === 'All') {
    return EVIDENCE_BASED_EXERCISES.filter((e) => e.rank <= limit);
  }

  // Handle plural / singular variations
  const normalized = muscleGroup.toLowerCase();
  return EVIDENCE_BASED_EXERCISES.filter((e) => {
    const eMuscle = e.muscleGroup.toLowerCase();
    if (normalized === 'shoulders' || normalized === 'shoulder') {
      return eMuscle === 'shoulders' || eMuscle === 'shoulder';
    }
    if (normalized === 'forearms' || normalized === 'forearm') {
      return eMuscle === 'forearms' || eMuscle === 'forearm';
    }
    if (normalized === 'legs') {
      return ['quads', 'hamstrings', 'glutes', 'calves'].includes(eMuscle);
    }
    return eMuscle === normalized;
  })
    .sort((a, b) => a.rank - b.rank)
    .slice(0, limit);
}
